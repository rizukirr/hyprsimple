#!/bin/bash

# Tested for before use, not sourced blind. A missing helper used to leave
# this script running with its functions undefined, delivering nothing and
# still reporting "Theme applied!" at the end.
# This one line cannot use require_helper, so it carries the check itself.
source "$HOME/.local/bin/hyprsimple-require.sh" 2>/dev/null || {
  echo "hyprsimple: missing helper: hyprsimple-require.sh. Run hyprsimple-update." >&2
  command -v notify-send >/dev/null &&
    notify-send -u critical "hyprsimple" "Missing helper: hyprsimple-require.sh. Run hyprsimple-update."
  exit 1
}
require_helper hypr-helpers.sh hyprsimple-theme-deliver.sh

# Usage: theme-switcher.sh [theme-name]
#   No argument: show rofi picker
#   With argument: apply theme directly (used by rofi script mode)

THEMES_DIR="$HOME/.config/hypr/themes"
CACHE_DIR="$HOME/.cache"
mkdir -p "$CACHE_DIR"

if [[ -n "$1" ]]; then
  THEME="$1"
else
  THEME=$("$HOME/.local/bin/hyprsimple-theme-picker.sh" |
    "$HOME/.local/bin/hyprsimple-image-picker.sh" --prompt "Theme" --columns 3)
fi
[[ -z "$THEME" ]] && exit 0

THEME_PATH="$THEMES_DIR/$THEME"

# 1. Generate configs from templates (if colors.toml exists)
if [[ -f "$THEME_PATH/colors.toml" ]]; then
  "$HOME/.local/bin/theme-apply-templates.sh" "$THEME_PATH"
fi

# 2 to 8. Every generated file the theme ships, put where its program reads it.
#
# Shared with hyprsimple-update.sh, which re-renders the templates when one
# changes and has to deliver the result the same way. It used to carry its own
# shorter list and so delivered two of the eight.
deliver_theme_configs "$THEME_PATH"

# 9. Wallpaper (copy so hyprpaper detects change)
WALLPAPER=""
if [[ -d "$THEME_PATH/backgrounds" ]]; then
  WALLPAPER=$(find "$THEME_PATH/backgrounds" -type f \( -name "*.png" -o -name "*.jpg" \) | sort | head -1)
elif [[ -f "$THEME_PATH/wallpaper.jpg" ]]; then
  WALLPAPER="$THEME_PATH/wallpaper.jpg"
fi
if [[ -n "$WALLPAPER" ]]; then
  rm -f "$CACHE_DIR/current_wallpaper"
  cp "$WALLPAPER" "$CACHE_DIR/current_wallpaper"
  echo "$WALLPAPER" > "$CACHE_DIR/current_wallpaper_path"

  # Use theme background as rofi launcher/powermenu image
  WP_EXT="${WALLPAPER##*.}"
  for rofi_type in launcher powermenu; do
    ROFI_TARGET="$HOME/.config/rofi/$rofi_type/images"
    mkdir -p "$ROFI_TARGET"
    [[ -L "$ROFI_TARGET" ]] && rm -f "$ROFI_TARGET" && mkdir -p "$ROFI_TARGET"
    rm -f "$ROFI_TARGET"/wallpaper.*
    ln -sf "$WALLPAPER" "$ROFI_TARGET/wallpaper.$WP_EXT"
    # Anchored on the closing quote, so only the url() reference is rewritten.
    #
    # Without it the pattern also matched the header of that same file, which
    # reads "the line naming images/wallpaper.<ext> is rewritten on every theme
    # switch... Everything else here is kept". [a-z]* matched nothing before
    # "<ext>", so every theme switch turned that into images/wallpaper.jpg<ext>,
    # and the one promise the file makes about itself was broken by the line it
    # was describing. Found already done on a live machine, in both style.rasi
    # files.
    #
    # It is not only cosmetic. style.rasi carries no "Do not edit this file"
    # header, so hyprsimple-update.sh counts it as the user's own copy: an
    # update that touches style.rasi would name it as a file they have their own
    # version of, over a difference hyprsimple made, and the refresh it suggests
    # would then replace their file.
    sed -i "s|images/wallpaper\.[a-z]*\"|images/wallpaper.$WP_EXT\"|" \
      "$HOME/.config/rofi/$rofi_type/style.rasi"
  done
fi

# Write hyprpaper.conf based on live wallpaper state
if [[ -f "$CACHE_DIR/live_wallpaper_enabled" && -d "$THEME_PATH/backgrounds" ]]; then
  write_hyprpaper_conf "$THEME_PATH/backgrounds" 30
else
  write_hyprpaper_conf "$HOME/.cache/current_wallpaper"
fi

# Lockscreen. The cache filename keeps its .png suffix because hyprlock.conf
# points at it by name. Hyprlock sniffs content, so a JPEG behind that name is
# fine, and the fallback below has always written one.
rm -f "$CACHE_DIR/current_lockscreen.png"
THEME_LOCKSCREEN=$(find "$THEME_PATH" -maxdepth 1 -type f -name 'lockscreen.*' | sort | head -1)
if [[ -n "$THEME_LOCKSCREEN" ]]; then
  cp "$THEME_LOCKSCREEN" "$CACHE_DIR/current_lockscreen.png"
elif [[ -n "$WALLPAPER" ]]; then
  cp "$WALLPAPER" "$CACHE_DIR/current_lockscreen.png"
fi

# 10. GTK/QT light/dark mode + Icon/Cursor settings
if [[ -f "$THEME_PATH/light.mode" ]]; then
  GTK_THEME_NAME="Adwaita"
  gsettings set org.gnome.desktop.interface color-scheme "prefer-light"
else
  GTK_THEME_NAME="Adwaita-dark"
  gsettings set org.gnome.desktop.interface color-scheme "prefer-dark"
fi

gsettings set org.gnome.desktop.interface gtk-theme "$GTK_THEME_NAME"

# Update gtk-3.0 and gtk-4.0 settings.ini (some apps read these instead of gsettings)
#
# This used to be a mkdir followed by `[[ -f settings.ini ]] && sed`, and
# nothing in hyprsimple has ever created settings.ini. So the mkdir made the
# directory, the test then failed, and the block wrote nothing on every theme
# switch. Measured on a live machine: ~/.config/gtk-3.0 and ~/.config/gtk-4.0
# both present and both empty, on an install that had switched themes many
# times. The apps the comment above is about were reading nothing.
#
# Three cases, because the file belongs to the user when it exists:
#   absent          write a minimal one
#   has the key     replace that line, keeping the rest
#   lacks the key   add it under [Settings], keeping the rest
set_gtk_theme_name() {
  local file="$1" name="$2"

  if [[ ! -f $file ]]; then
    printf '[Settings]\ngtk-theme-name=%s\n' "$name" >"$file"
    return 0
  fi

  # Section aware, because settings.ini is an ini file and the key only counts
  # under [Settings]. A first attempt matched ^gtk-theme-name= anywhere, which
  # rewrote one sitting under a later section and left [Settings] without the
  # key. That is the same unanchored-match mistake this file just had in its
  # rofi rewrite.
  local tmp="$file.hyprsimple.$$"
  awk -v name="$name" '
    /^[[:space:]]*\[/ {
      # Leaving [Settings] without having seen the key: add it here.
      if (in_settings && !done) { print "gtk-theme-name=" name; done = 1 }
      in_settings = ($0 ~ /^[[:space:]]*\[Settings\][[:space:]]*$/)
      if (in_settings) seen_settings = 1
      print
      next
    }
    in_settings && /^[[:space:]]*gtk-theme-name[[:space:]]*=/ {
      if (!done) { print "gtk-theme-name=" name; done = 1 }
      next
    }
    { print }
    END {
      if (!done) {
        if (in_settings) print "gtk-theme-name=" name
        else if (!seen_settings) { print ""; print "[Settings]"; print "gtk-theme-name=" name }
      }
    }
  ' "$file" >"$tmp" || { rm -f "$tmp"; return 0; }

  # A [Settings] section that ended before EOF and got no key would leave the
  # file without one. awk above adds it on the section boundary, so this only
  # guards the case where awk wrote nothing at all.
  if [[ -s $tmp ]]; then
    mv -f "$tmp" "$file"
  else
    rm -f "$tmp"
  fi
}

for gtk_dir in "$HOME/.config/gtk-3.0" "$HOME/.config/gtk-4.0"; do
  mkdir -p "$gtk_dir"
  set_gtk_theme_name "$gtk_dir/settings.ini" "$GTK_THEME_NAME"
done

# Icon theme (icons.theme = omarchy style, icon-theme = hyprsimple style)
if [[ -f "$THEME_PATH/icons.theme" ]]; then
  gsettings set org.gnome.desktop.interface icon-theme "$(cat "$THEME_PATH/icons.theme")"
elif [[ -f "$THEME_PATH/icon-theme" ]]; then
  gsettings set org.gnome.desktop.interface icon-theme "$(cat "$THEME_PATH/icon-theme")"
fi

# Replace one export in uwsm/env rather than appending another. The file is
# read once at login, so a second export of the same name would win silently
# and the file would grow a line per theme switch.
set_session_env() {
  local name="$1" value="$2"
  local file="$HOME/.config/uwsm/env"
  [[ -f $file ]] || return 0
  local tmp="$file.tmp.$$"
  grep -v "^export $name=" "$file" >"$tmp" || true
  printf 'export %s=%s\n' "$name" "$value" >>"$tmp"
  mv "$tmp" "$file"
}

# A cursor theme is a directory with a cursors/ subdirectory in one of the
# icon paths. Anything else is a name, not a theme.
#
# Checked because nothing else does. hyprctl setcursor answers "ok" for a theme
# that is not installed, and gsettings stores whatever it is given, so two
# shipped themes carried values that had never worked and nothing reported it:
# catppuccin asked for catppuccin-mocha-lavender-cursors, which is in no
# package list and no repository, and rosepine asked for Adwaita-dark, which is
# a GTK theme name rather than a cursor theme. The only cursor themes on a
# hyprsimple machine are Adwaita and Yaru.
#
# It matters past the switch: XCURSOR_THEME is written to uwsm/env and read at
# every login, so a name that resolves to nothing outlives the theme that set
# it, which is the opposite of what that export is for.
cursor_theme_exists() {
  local name="$1" dir
  for dir in "$HOME/.local/share/icons" "$HOME/.icons" /usr/share/icons; do
    [[ -d $dir/$name/cursors ]] && return 0
  done
  return 1
}

if [[ -f "$THEME_PATH/cursor-theme" ]]; then
  CURSOR="$(cat "$THEME_PATH/cursor-theme")"
fi

if [[ -n ${CURSOR:-} ]] && ! cursor_theme_exists "$CURSOR"; then
  echo "theme-switcher: cursor theme '$CURSOR' is not installed, leaving the cursor alone" >&2
  notify-send "Theme Manager" "Cursor theme '$CURSOR' is not installed, so the cursor was left as it is" >/dev/null 2>&1
  CURSOR=""
fi

if [[ -n ${CURSOR:-} ]]; then
  gsettings set org.gnome.desktop.interface cursor-theme "$CURSOR"
  [[ -z "$THEME_SWITCHER_NO_RELOAD" ]] && hyprctl setcursor "$CURSOR" 24

  # gsettings reaches GTK and `hyprctl setcursor` reaches Hyprland, but only
  # until logout. XCURSOR_THEME is what survives a login and what XWayland, SDL
  # and Qt read, and nothing here ever wrote it: install.sh wrote it once, and
  # only if the theme it installed with declared a cursor. The default theme is
  # deep-sea, which does not, so on a fresh install it was never set at all,
  # and switching to a theme that does declare one did not set it either.
  set_session_env XCURSOR_THEME "$CURSOR"
fi

# 11. Reload Services (skipped during install via THEME_SWITCHER_NO_RELOAD=1)
if [[ -z "$THEME_SWITCHER_NO_RELOAD" ]]; then
  hyprctl reload

  systemctl --user restart hyprpaper.service

  "$HOME/.local/bin/hyprsimple-restart-waybar.sh" --if-running

  "$HOME/.local/bin/hyprsimple-restart-dunst.sh" --if-running

  notify-send "Theme Manager" "Theme '$THEME' applied!" -i "$CACHE_DIR/current_wallpaper"
fi
